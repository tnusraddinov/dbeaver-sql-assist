package com.sqlassist.dbeaver.validation;

/**
 * Database-independent description of a table column, filled from DBeaver metadata.
 *
 * @param maxLength character limit for CHAR/VARCHAR-like types, or -1 when not applicable
 */
public record ColumnMeta(String name, String typeName, Kind kind, long maxLength,
                         boolean required, boolean hasDefault, boolean autoGenerated) {

    public enum Kind { INTEGER, DECIMAL, STRING, BOOLEAN, DATETIME, BINARY, OTHER }

    /** NOT NULL, no default and not generated: the INSERT must supply a value. */
    public boolean mustBeProvided() {
        return required && !hasDefault && !autoGenerated;
    }

    /** Type as shown to the user, e.g. {@code varchar(50)}, {@code int4}. */
    public String typeLabel() {
        return typeName + (maxLength > 0 && kind == Kind.STRING && !typeName.contains("(") ? "(" + maxLength + ")" : "");
    }

    public String describe() {
        return name + " " + typeLabel();
    }
}
