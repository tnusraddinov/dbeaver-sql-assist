package com.sqlassist.dbeaver.validation;

import com.sqlassist.dbeaver.parser.InsertStatement;
import com.sqlassist.dbeaver.parser.Span;
import com.sqlassist.dbeaver.validation.Problem.Severity;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Module 3: checks an INSERT against table metadata. Pure function, no DBeaver calls.
 * Only literal values are judged; expressions are trusted, to avoid false alarms.
 */
public final class InsertValidator {

    private static final Set<String> BOOLEAN_STRINGS = Set.of(
            "true", "false", "t", "f", "yes", "no", "y", "n", "1", "0", "on", "off");

    private InsertValidator() {
    }

    public static List<Problem> validate(InsertStatement statement, CharSequence text, TableMeta table) {
        List<Problem> problems = new ArrayList<>();
        List<ColumnMeta> targets = new ArrayList<>(); // per position; null = unknown column

        if (statement.hasColumnList()) {
            Set<String> seen = new HashSet<>();
            for (Span span : statement.columns()) {
                String written = span.text(text);
                ColumnMeta column = table.find(written).orElse(null);
                targets.add(column);
                if (span.length() == 0) {
                    continue;
                }
                if (column == null) {
                    problems.add(new Problem(span, Severity.ERROR,
                            "Column " + written + " does not exist in " + table.name()));
                } else if (!seen.add(column.name().toLowerCase(Locale.ROOT))) {
                    problems.add(new Problem(span, Severity.ERROR, "Column " + column.name() + " is listed twice"));
                }
            }
            List<String> missing = new ArrayList<>();
            for (ColumnMeta c : table.columns()) {
                if (c.mustBeProvided() && !seen.contains(c.name().toLowerCase(Locale.ROOT))) {
                    missing.add(c.describe());
                }
            }
            if (!missing.isEmpty()) {
                problems.add(new Problem(statement.tableNameSpan(), Severity.WARNING,
                        (missing.size() == 1 ? "NOT NULL column without default is missing: "
                                : "NOT NULL columns without default are missing: ") + String.join(", ", missing)));
            }
        } else {
            targets.addAll(table.columns());
        }

        int expected = targets.size();
        for (int r = 0; r < statement.rows().size(); r++) {
            List<Span> row = statement.rows().get(r);
            String rowName = statement.rows().size() > 1 ? "Row " + (r + 1) : "VALUES";
            if (row.size() < expected && statement.sourceKind() == InsertStatement.SourceKind.VALUES) {
                Span at = row.isEmpty() ? statement.tableNameSpan() : row.get(row.size() - 1);
                problems.add(new Problem(at, Severity.ERROR, rowName + " has " + row.size() + " values but "
                        + expected + (statement.hasColumnList() ? " columns are listed" : " columns exist in " + table.name())));
            }
            for (int i = 0; i < row.size(); i++) {
                Span value = row.get(i);
                if (i >= expected) {
                    problems.add(new Problem(value, Severity.ERROR, "No column for this value ("
                            + rowName.toLowerCase(Locale.ROOT) + " has " + row.size() + " values, " + expected
                            + (statement.hasColumnList() ? " columns listed)" : " columns in table)")));
                    continue;
                }
                ColumnMeta column = targets.get(i);
                if (column != null && value.length() > 0) {
                    checkValue(column, value, Literal.of(value.text(text)), problems);
                }
            }
        }
        return problems;
    }

    private static void checkValue(ColumnMeta c, Span span, Literal literal, List<Problem> problems) {
        switch (literal.kind()) {
            case NULL -> {
                if (c.required() && !c.autoGenerated()) {
                    problems.add(new Problem(span, Severity.ERROR, "Column " + c.describe() + " is NOT NULL"));
                }
            }
            case STRING -> checkString(c, span, literal.value(), problems);
            case NUMBER -> checkNumber(c, span, literal.value(), problems);
            default -> {
                // DEFAULT, booleans, expressions: nothing reliable to check.
            }
        }
    }

    private static void checkString(ColumnMeta c, Span span, String value, List<Problem> problems) {
        String trimmed = value.strip();
        switch (c.kind()) {
            case INTEGER -> {
                if (Literal.isInteger(trimmed)) {
                    problems.add(new Problem(span, Severity.WARNING,
                            "String literal for " + c.describe() + " relies on implicit conversion; write " + trimmed));
                } else {
                    problems.add(new Problem(span, Severity.ERROR,
                            "'" + abbreviate(value) + "' is not a valid integer for " + c.describe()));
                }
            }
            case DECIMAL -> {
                if (Literal.isNumeric(trimmed)) {
                    problems.add(new Problem(span, Severity.WARNING,
                            "String literal for " + c.describe() + " relies on implicit conversion; write " + trimmed));
                } else {
                    problems.add(new Problem(span, Severity.ERROR,
                            "'" + abbreviate(value) + "' is not a valid number for " + c.describe()));
                }
            }
            case STRING -> {
                int length = value.codePointCount(0, value.length());
                if (c.maxLength() > 0 && length > c.maxLength()) {
                    problems.add(new Problem(span, Severity.ERROR, "Value is " + length
                            + " characters; " + c.describe() + " allows " + c.maxLength()));
                }
            }
            case BOOLEAN -> {
                if (!BOOLEAN_STRINGS.contains(trimmed.toLowerCase(Locale.ROOT))) {
                    problems.add(new Problem(span, Severity.ERROR,
                            "'" + abbreviate(value) + "' is not a valid boolean for " + c.describe()));
                }
            }
            case DATETIME -> {
                if (!looksLikeDateTime(trimmed)) {
                    problems.add(new Problem(span, Severity.WARNING,
                            "'" + abbreviate(value) + "' does not look like a date/time for " + c.describe()));
                }
            }
            default -> {
            }
        }
    }

    private static void checkNumber(ColumnMeta c, Span span, String value, List<Problem> problems) {
        switch (c.kind()) {
            case INTEGER -> {
                if (!Literal.isInteger(value)) {
                    problems.add(new Problem(span, Severity.WARNING,
                            value + " has a fractional part; " + c.describe() + " stores whole numbers"));
                }
            }
            case STRING -> {
                if (c.maxLength() > 0 && value.length() > c.maxLength()) {
                    problems.add(new Problem(span, Severity.ERROR, "Value is " + value.length()
                            + " characters; " + c.describe() + " allows " + c.maxLength()));
                }
            }
            case BOOLEAN -> {
                if (!value.equals("0") && !value.equals("1")) {
                    problems.add(new Problem(span, Severity.WARNING, value + " is not 0 or 1 for " + c.describe()));
                }
            }
            case DATETIME -> problems.add(new Problem(span, Severity.WARNING,
                    "Number used for " + c.describe() + "; use a date/time literal"));
            default -> {
            }
        }
    }

    /** Accepts ISO-like dates/times (2024-01-31, 2024-01-31 10:00, 10:00:00, 20240131). */
    private static boolean looksLikeDateTime(String s) {
        return s.matches("\\d{4}-\\d{1,2}-\\d{1,2}([ T].*)?")
                || s.matches("\\d{1,2}:\\d{2}(:\\d{2}(\\.\\d+)?)?.*")
                || s.matches("\\d{8}([ T].*)?")
                || s.matches("\\d{1,2}[./]\\d{1,2}[./]\\d{2,4}.*")
                || s.equalsIgnoreCase("now") || s.equalsIgnoreCase("today") || s.equalsIgnoreCase("infinity")
                || s.equalsIgnoreCase("-infinity");
    }

    private static String abbreviate(String s) {
        String one = s.replaceAll("\\s+", " ");
        return one.length() > 30 ? one.substring(0, 27) + "..." : one;
    }
}
